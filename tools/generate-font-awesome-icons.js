"use strict";

const fs = require("node:fs");
const path = require("node:path");
const solid = require("@fortawesome/free-solid-svg-icons");
const regular = require("@fortawesome/free-regular-svg-icons");
const mdi = require("@mdi/js");

const root = path.resolve(__dirname, "..");
const fontAwesomeVersion = JSON.parse(
  fs.readFileSync(
    path.join(
      root,
      "node_modules",
      "@fortawesome",
      "free-solid-svg-icons",
      "package.json",
    ),
    "utf8",
  ),
).version;
const mdiVersion = JSON.parse(
  fs.readFileSync(path.join(root, "node_modules", "@mdi", "js", "package.json"), "utf8"),
).version;
const bootstrapVersion = JSON.parse(
  fs.readFileSync(path.join(root, "node_modules", "bootstrap-icons", "package.json"), "utf8"),
).version;

function titleCase(value) {
  return String(value)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .split(/\s+/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function collect(pack, prefix, style) {
  const unique = new Map();
  Object.values(pack).forEach((definition) => {
    if (definition && definition.iconName && !unique.has(definition.iconName))
      unique.set(definition.iconName, definition);
  });
  return [...unique.values()].map((definition) => {
    const [width, height, aliases, , paths] = definition.icon;
    return [
      `${prefix}:${definition.iconName}`,
      width,
      height,
      paths,
      titleCase(definition.iconName),
      `Font Awesome ${style}`,
      (aliases || []).filter((alias) => typeof alias === "string").join(" "),
    ];
  });
}

function collectMdi() {
  return Object.entries(mdi)
    .filter(([key, value]) => /^mdi[A-Z]/.test(key) && typeof value === "string")
    .map(([key, value]) => {
      const name = key.slice(3).replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
      return [`mdi:${name}`, 24, 24, value, titleCase(key.slice(3)), "Material Design Icons", "home automation av pictogrammers"];
    });
}

function collectBootstrap() {
  const folder = path.join(root, "node_modules", "bootstrap-icons", "icons");
  return fs.readdirSync(folder)
    .filter((file) => file.endsWith(".svg"))
    .map((file) => {
      const name = path.basename(file, ".svg"),
        source = fs.readFileSync(path.join(folder, file), "utf8"),
        match = source.match(/<svg[^>]*viewBox="0 0 ([\d.]+) ([\d.]+)"[^>]*>([\s\S]*?)<\/svg>/i);
      if (!match) throw new Error(`Bootstrap icon ${file} has no supported viewBox.`);
      const body = match[3].replace(/<title>[\s\S]*?<\/title>/gi, "").trim();
      return [`bi:${name}`, Number(match[1]), Number(match[2]), body, titleCase(name), "Bootstrap Icons", "bootstrap clean interface controls"];
    });
}

const records = [
  ...collect(solid.fas, "fa-solid", "Solid"),
  ...collect(regular.far, "fa-regular", "Regular"),
  ...collectMdi(),
  ...collectBootstrap(),
].sort((a, b) => a[4].localeCompare(b[4]) || a[5].localeCompare(b[5]));

const versions = { fontAwesome: fontAwesomeVersion, mdi: mdiVersion, bootstrap: bootstrapVersion };
const source = `/* Generated by tools/generate-font-awesome-icons.js from Font Awesome Free ${fontAwesomeVersion}, Material Design Icons ${mdiVersion}, and Bootstrap Icons ${bootstrapVersion}.\n` +
  ` * Licenses: Font Awesome Free CC BY 4.0; MDI Apache 2.0; Bootstrap Icons MIT. */\n` +
  `(function(global){"use strict";var rows=${JSON.stringify(records)},definitions=Object.fromEntries(rows.map(function(row){return[row[0],row.slice(1)]}));` +
  `function escapeAttribute(value){return String(value||"").replace(/&/g,"&amp;").replace(/"/g,"&quot;").replace(/</g,"&lt;")}` +
  `function get(value){return definitions[String(value||"").replace(/^fas:/,"fa-solid:").replace(/^far:/,"fa-regular:")]||null}` +
  `function paths(record){var value=record&&record[2];if(typeof value==='string'&&value.trim().charAt(0)==='<')return value;return(Array.isArray(value)?value:[value]).filter(Boolean).map(function(path,index){return'<path fill="currentColor" stroke="none"'+(index?' opacity=".4"':'')+' d="'+escapeAttribute(path)+'"></path>'}).join("")}` +
  `function svg(value,options){options=options||{};var record=get(value),className=options.className?' class="'+escapeAttribute(options.className)+'"':'',label=options.label?' aria-label="'+escapeAttribute(options.label)+'" role="img"':' aria-hidden="true"',body,viewBox;if(record){viewBox='0 0 '+record[0]+' '+record[1];body=paths(record)}else{viewBox=options.viewBox||'0 0 24 24';body=(options.legacy&&options.legacy[value])||(options.legacy&&options.legacy[options.fallback])||options.body||''}return'<svg'+className+' viewBox="'+viewBox+'"'+label+' fill="currentColor" focusable="false">'+body+'</svg>'}` +
  `function options(){return rows.map(function(row){return{value:row[0],label:row[4]+' — '+row[5],name:row[4],style:row[5],search:(row[4]+' '+row[0]+' '+row[5]+' '+row[6]).toLowerCase()}})}` +
  `function pick(values){var result={};(values||[]).forEach(function(value){var key=String(value||"").replace(/^fas:/,"fa-solid:").replace(/^far:/,"fa-regular:"),record=definitions[key];if(record)result[key]=record.slice(0,3)});return result}` +
  `global.ComposerIcons={version:${JSON.stringify(fontAwesomeVersion)},versions:${JSON.stringify(versions)},get:get,svg:svg,options:options,pick:pick,definitions:definitions};})(window);\n`;

fs.writeFileSync(path.join(root, "font-awesome-free-icons.js"), source);
fs.copyFileSync(
  path.join(root, "node_modules", "@fortawesome", "free-solid-svg-icons", "LICENSE.txt"),
  path.join(root, "FONT-AWESOME-FREE-LICENSE.txt"),
);
fs.copyFileSync(path.join(root, "node_modules", "@mdi", "js", "LICENSE"), path.join(root, "MATERIAL-DESIGN-ICONS-LICENSE.txt"));
fs.copyFileSync(path.join(root, "node_modules", "bootstrap-icons", "LICENSE"), path.join(root, "BOOTSTRAP-ICONS-LICENSE.txt"));
console.log(`Generated ${records.length} icons from Font Awesome, Material Design Icons, and Bootstrap Icons.`);
