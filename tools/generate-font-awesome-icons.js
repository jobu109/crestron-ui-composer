"use strict";

const fs = require("node:fs");
const path = require("node:path");
const solid = require("@fortawesome/free-solid-svg-icons");
const regular = require("@fortawesome/free-regular-svg-icons");

const root = path.resolve(__dirname, "..");
const version = JSON.parse(
  fs.readFileSync(
    path.join(
      root,
      "node_modules",
      "@fortawesome",
      "free-solid-svg-icons",
      "package.json",
    ),
    "utf8",
  ),
).version;

function titleCase(value) {
  return String(value)
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function collect(pack, prefix, style) {
  const unique = new Map();
  Object.values(pack).forEach((definition) => {
    if (definition && definition.iconName && !unique.has(definition.iconName))
      unique.set(definition.iconName, definition);
  });
  return [...unique.values()].map((definition) => {
    const [width, height, aliases, , paths] = definition.icon;
    return [
      `${prefix}:${definition.iconName}`,
      width,
      height,
      paths,
      titleCase(definition.iconName),
      style,
      (aliases || []).filter((alias) => typeof alias === "string").join(" "),
    ];
  });
}

const records = [
  ...collect(solid.fas, "fa-solid", "Solid"),
  ...collect(regular.far, "fa-regular", "Regular"),
].sort((a, b) => a[4].localeCompare(b[4]) || a[5].localeCompare(b[5]));

const source = `/* Generated by tools/generate-font-awesome-icons.js from Font Awesome Free ${version}.\n` +
  ` * Icons: CC BY 4.0. See FONT-AWESOME-FREE-LICENSE.txt. */\n` +
  `(function(global){"use strict";var rows=${JSON.stringify(records)},definitions=Object.fromEntries(rows.map(function(row){return[row[0],row.slice(1)]}));` +
  `function escapeAttribute(value){return String(value||"").replace(/&/g,"&amp;").replace(/"/g,"&quot;").replace(/</g,"&lt;")}` +
  `function get(value){return definitions[String(value||"").replace(/^fas:/,"fa-solid:").replace(/^far:/,"fa-regular:")]||null}` +
  `function paths(record){var value=record&&record[2];return(Array.isArray(value)?value:[value]).filter(Boolean).map(function(path,index){return'<path fill="currentColor" stroke="none"'+(index?' opacity=".4"':'')+' d="'+escapeAttribute(path)+'"></path>'}).join("")}` +
  `function svg(value,options){options=options||{};var record=get(value),className=options.className?' class="'+escapeAttribute(options.className)+'"':'',label=options.label?' aria-label="'+escapeAttribute(options.label)+'" role="img"':' aria-hidden="true"',body,viewBox;if(record){viewBox='0 0 '+record[0]+' '+record[1];body=paths(record)}else{viewBox=options.viewBox||'0 0 24 24';body=(options.legacy&&options.legacy[value])||(options.legacy&&options.legacy[options.fallback])||options.body||''}return'<svg'+className+' viewBox="'+viewBox+'"'+label+' focusable="false">'+body+'</svg>'}` +
  `function options(){return rows.map(function(row){return{value:row[0],label:row[4]+' — Font Awesome '+row[5],name:row[4],style:row[5],search:(row[4]+' '+row[0]+' '+row[6]).toLowerCase()}})}` +
  `function pick(values){var result={};(values||[]).forEach(function(value){var key=String(value||"").replace(/^fas:/,"fa-solid:").replace(/^far:/,"fa-regular:"),record=definitions[key];if(record)result[key]=record.slice(0,3)});return result}` +
  `global.ComposerIcons={version:${JSON.stringify(version)},get:get,svg:svg,options:options,pick:pick,definitions:definitions};})(window);\n`;

fs.writeFileSync(path.join(root, "font-awesome-free-icons.js"), source);
fs.copyFileSync(
  path.join(root, "node_modules", "@fortawesome", "free-solid-svg-icons", "LICENSE.txt"),
  path.join(root, "FONT-AWESOME-FREE-LICENSE.txt"),
);
console.log(`Generated ${records.length} Font Awesome Free icons.`);
